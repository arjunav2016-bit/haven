package haven.pattern.report;

import haven.model.Accommodation;
import haven.model.Enquiry;
import haven.model.Hostel;
import haven.model.Review;
import haven.model.User;

import java.util.List;

/**
 * Concrete ReportGenerator (Template Method Pattern) producing a comprehensive
 * System Governance &amp; Analytics Audit Report for Administrators and Owners.
 */
public class SystemAnalyticsReport extends ReportGenerator {
    private final List<User> users;
    private final List<Accommodation> accommodations;
    private final List<Enquiry> enquiries;
    private final List<Review> reviews;

    public SystemAnalyticsReport(List<User> users, List<Accommodation> accommodations,
                                 List<Enquiry> enquiries, List<Review> reviews) {
        this.users = users;
        this.accommodations = accommodations;
        this.enquiries = enquiries;
        this.reviews = reviews;
    }

    @Override
    protected String buildHeaderBanner() {
        return "                          HAVEN PLATFORM GOVERNANCE                             \n" +
               "                   SYSTEM-WIDE ANALYTICS & AUDIT SUMMARY                        \n";
    }

    @Override
    protected String buildMetadataSection() {
        StringBuilder sb = new StringBuilder();
        sb.append(String.format("Report Generated : %s\n", formatNow()));
        sb.append(String.format("Total Users      : %d\n", users != null ? users.size() : 0));
        sb.append(String.format("Total Listings   : %d\n", accommodations != null ? accommodations.size() : 0));
        sb.append(String.format("Total Enquiries  : %d\n", enquiries != null ? enquiries.size() : 0));
        sb.append(String.format("Total Reviews    : %d\n", reviews != null ? reviews.size() : 0));
        sb.append(SEPARATOR_SINGLE);
        return sb.toString();
    }

    @Override
    protected String buildBodyContent() {
        StringBuilder sb = new StringBuilder();
        int hostelsCount = 0;
        int pgCount = 0;
        int totalVacancies = 0;
        double estCapacityValue = 0.0;

        if (accommodations != null) {
            for (Accommodation a : accommodations) {
                if (a instanceof Hostel) hostelsCount++;
                else pgCount++;
                totalVacancies += a.getVacancies();
                estCapacityValue += a.calculateTotalMonthlyCost(1) * Math.max(1, a.getVacancies());
            }
        }

        sb.append("ACCOMMODATION INVENTORY METRICS:\n");
        sb.append(String.format("  Approved Hostels        : %d\n", hostelsCount));
        sb.append(String.format("  Paying Guest (PG) Stays : %d\n", pgCount));
        sb.append(String.format("  Available Bed Vacancies : %d\n", totalVacancies));
        sb.append(String.format("  Est. Monthly Inventory  : Rs. %,.0f\n", estCapacityValue));
        sb.append(SEPARATOR_SINGLE);

        int pending = 0, contacted = 0, confirmed = 0, declined = 0, cancelled = 0;
        if (enquiries != null) {
            for (Enquiry e : enquiries) {
                String st = e.getStatus().toUpperCase();
                switch (st) {
                    case "PENDING": pending++; break;
                    case "CONTACTED": contacted++; break;
                    case "CONFIRMED": confirmed++; break;
                    case "DECLINED": declined++; break;
                    case "CANCELLED": cancelled++; break;
                }
            }
        }

        sb.append("ENQUIRY PIPELINE BREAKDOWN:\n");
        sb.append(String.format("  Pending Applications    : %d\n", pending));
        sb.append(String.format("  Contacted by Warden     : %d\n", contacted));
        sb.append(String.format("  Confirmed Bookings      : %d\n", confirmed));
        sb.append(String.format("  Declined Applications   : %d\n", declined));
        sb.append(String.format("  Cancelled by Student    : %d\n", cancelled));
        sb.append(SEPARATOR_SINGLE);
        return sb.toString();
    }

    @Override
    protected String buildFooterSection() {
        return "Generated by HAVEN Platform Administration Module.\n";
    }
}
